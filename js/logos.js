/**
 * İsme ve kategoriye göre dinamik şık monogram logo SVG üretir
 */
function createMonogramSVG(name, category = 'shop') {
  const cleanName = (name || 'M').replace(/[^a-zA-Z0-9ğüşıöçĞÜŞİÖÇ\s]/g, '').trim();
  const words = cleanName.split(/\s+/).filter(Boolean);
  let letters = '';
  if (words.length >= 2) {
    letters = (words[0][0] + words[1][0]).toUpperCase();
  } else if (words.length === 1 && words[0].length >= 2) {
    letters = words[0].substring(0, 2).toUpperCase();
  } else {
    letters = (words[0] || 'M').toUpperCase();
  }

  const themes = {
    fashion: { bg: '#8B5CF6', text: '#FFFFFF' },
    food: { bg: '#F97316', text: '#FFFFFF' },
    tech: { bg: '#06B6D4', text: '#FFFFFF' },
    cosmetics: { bg: '#EC4899', text: '#FFFFFF' },
    sports: { bg: '#10B981', text: '#FFFFFF' },
    home: { bg: '#EAB308', text: '#FFFFFF' },
    entertainment: { bg: '#F43F5E', text: '#FFFFFF' },
    service: { bg: '#64748B', text: '#FFFFFF' },
    atm: { bg: '#3B82F6', text: '#FFFFFF' },
    wc: { bg: '#0284C7', text: '#FFFFFF' }
  };

  const theme = themes[category] || themes.fashion;
  const fontSize = letters.length > 1 ? 36 : 46;

  return `<svg viewBox="0 0 100 100" class="w-full h-full" xmlns="http://www.w3.org/2000/svg">
    <rect width="100" height="100" rx="22" fill="${theme.bg}"/>
    <text x="50" y="60" font-family="'Outfit', -apple-system, sans-serif" font-weight="900" font-size="${fontSize}" fill="${theme.text}" text-anchor="middle" letter-spacing="-0.5">${letters}</text>
  </svg>`;
}

